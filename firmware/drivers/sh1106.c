/* One display data transfer: the control byte and a page. Static: frame-sized buffers stay off the stack (NCR-023) */
static uint8_t io[1 + SH1106_WIDTH];

static int send(sh1106_t *d, const uint8_t *data, size_t len)
{
    return d->write(d->ctx, d->addr, data, len) == 0 ? SH1106_OK : SH1106_ERR_I2C;
}

static int select_page(sh1106_t *d, unsigned page)
{
    const uint8_t cmd[4] = {SH1106_CTRL_CMD, (uint8_t)(SH1106_CMD_PAGE | page),
                            SH1106_CMD_COL_LOW | (SH1106_COL_OFFSET & 0x0F), SH1106_CMD_COL_HIGH | (SH1106_COL_OFFSET >> 4)};
    return send(d, cmd, sizeof(cmd));
}

int sh1106_init(sh1106_t *d)
{
    static const uint8_t setup[] = {
        SH1106_CTRL_CMD,
        SH1106_CMD_DISPLAY_OFF,
        SH1106_CMD_CLOCK, 0x80,      /* the reset value: oscillator +15 %, divide by 1 */
        SH1106_CMD_MULTIPLEX, 0x3F,  /* 64 rows */
        SH1106_CMD_OFFSET, 0x00,
        SH1106_CMD_START_LINE | 0,
        SH1106_CMD_DCDC, 0x8B,       /* the built-in charge pump on */
        SH1106_CMD_PUMP_VOLT | 2,    /* 8.0 V */
        SH1106_CMD_SEG_REMAP,
        SH1106_CMD_COM_REMAP,
        SH1106_CMD_COM_PINS, 0x12,   /* alternative COM pin layout, as these panels are wired */
        SH1106_CMD_CONTRAST, 0x80,
        SH1106_CMD_PRECHARGE, 0x22,  /* the reset values */
        SH1106_CMD_VCOM, 0x35,
        SH1106_CMD_ALL_ON_OFF,
        SH1106_CMD_NORMAL,
    };
    static const uint8_t on[] = {SH1106_CTRL_CMD, SH1106_CMD_DISPLAY_ON};
    unsigned page;
    int      rc = send(d, setup, sizeof(setup));

    /* Clear all 132 columns, so the two hidden ones at each side never show stale memory after a mode change */
    for (page = 0; rc == SH1106_OK && page < SH1106_PAGES; page++)
    {
        const uint8_t cmd[4] = {SH1106_CTRL_CMD, (uint8_t)(SH1106_CMD_PAGE | page), SH1106_CMD_COL_LOW,
                                SH1106_CMD_COL_HIGH};
        uint8_t       blank[1 + SH1106_RAM_COLS - SH1106_WIDTH];

        rc = send(d, cmd, sizeof(cmd));
        memset(io, 0, sizeof(io));
        io[0] = SH1106_CTRL_DATA;
        if (rc == SH1106_OK)
        {
            rc = send(d, io, sizeof(io)); /* columns 0 to 127 */
        }
        memset(blank, 0, sizeof(blank));
        blank[0] = SH1106_CTRL_DATA;
        if (rc == SH1106_OK)
        {
            rc = send(d, blank, sizeof(blank)); /* 128 to 131 */
        }
    }
    return rc == SH1106_OK ? send(d, on, sizeof(on)) : rc;
}

int sh1106_write_page(sh1106_t *d, unsigned page, const uint8_t data[SH1106_WIDTH])
{
    int rc;

    if (page >= SH1106_PAGES)
    {
        return SH1106_ERR_ARG;
    }
    rc = select_page(d, page);
    if (rc != SH1106_OK)
    {
        return rc;
    }
    io[0] = SH1106_CTRL_DATA;
    memcpy(&io[1], data, SH1106_WIDTH);
    return send(d, io, sizeof(io));
}

const uint8_t *sh1106_glyph(char c)
{
    return font[(c < 0x20 || c > 0x7E) ? '?' - 0x20 : c - 0x20];
}

void sh1106_text(sh1106_frame_t fb, unsigned line, const char *s)
{
    unsigned i;

    if (line >= SH1106_LINES)
    {
        return;
    }
    memset(fb[line], 0, SH1106_WIDTH);
    for (i = 0; i < SH1106_COLS && s[i] != '\0'; i++)
    {
        memcpy(&fb[line][i * 6], sh1106_glyph(s[i]), 5);
    }
}
