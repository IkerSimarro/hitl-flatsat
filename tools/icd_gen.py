def md_table(fields, base):
    o = ["| Offset | Size | Field | Type | Units | Description |", "|---|---|---|---|---|---|"]
    for f in fields:
        t = f["type"] + (f"[{f['count']}]" if f["count"] > 1 or f["type"] == "char" else "")
        desc = f.get("desc", "")
        if "enum" in f:
            desc = (desc + f" Enum `{f['enum']}`.").strip()
        o.append(f"| {base + f['offset']} | {f['size']} | `{f['name']}` | {t} | {f.get('units', '')} | {desc} |")
    return o


def gen_markdown(icd):
    o = ["# HITL FlatSat — Byte-Level Layouts", "",
         f"> {HEADER_NOTE}", "",
         f"ICD data version {icd['version']}. Offsets are from the start of the packet (telemetry and commands) "
         "or the start of the CAN data field. Header layouts are in ICD.md §3.", "",
         "## Enumerations", ""]
    for name, e in icd["enums"].items():
        vals = ", ".join(f"`{k}` = {v}" for k, v in e["values"].items())
        o.append(f"- **{name}**: {vals}")
    o += ["", "## Telemetry packets", ""]
    for p in icd["tlm"]:
        o += [f"### `{p['name']}` — MID `0x{p['mid']:04X}`, {p['total_len']} bytes", "", p["desc"], ""]
        o += md_table(p["fields"], TLM_HDR_LEN) + [""]
    o += ["## Commands", ""]
    for c in icd["cmds"]:
        o += [f"### `{c['name']}` — MID `0x{c['mid']:04X}`, FC {c['fc']}, {c['total_len']} bytes", ""]
        o += (md_table(c["fields"], CMD_HDR_LEN) if c["fields"] else ["No arguments."]) + [""]
    o += ["## CAN messages", ""]
    for m in icd["can"]:
        src = "any node" if m["src"] == "ANY" else m["src"]
        ident = f"`0x{m['type'] << 4:03X}` + node" if m["src"] == "ANY" else \
            f"`0x{(m['type'] << 4) | icd['enums']['node']['values'][m['src']]:03X}`"
        period = f"{m['period_ms']} ms" if m["period_ms"] else "event"
        o += [f"### `{m['name']}` — type `0x{m['type']:02X}`, ID {ident}, DLC {m['dlc']}, from {src}, {period}", ""]
        o += md_table(m["fields"], 0) + [""]
    return "\n".join(o)


