def py_fmt(fields):
    fmt = "<"
    names = []
    for f in fields:
        code = TYPES[f["type"]][2]
        if f["type"] == "char":
            fmt += f"{f['count']}s"
            names.append(f["name"])
        else:
            fmt += code * f["count"]
            names += [f["name"]] if f["count"] == 1 else [f"{f['name']}_{i}" for i in range(f["count"])]
    return fmt, names


PY_RUNTIME = '''
TLM_HEADER = struct.Struct(">HHHIHI")
CMD_HEADER = struct.Struct(">HHHBB")


def can_id(msg_type, node):
    return (msg_type << 4) | node


def _checksum(packet):
    x = 0
    for b in packet:
        x ^= b
    return x ^ 0xFF


def build_command(name, seq=0, **args):
    """Encode a command (e.g. build_command("OBC_SET_MODE", MODE=1)) with a valid checksum."""
    mid, fc, fmt, names = CMD[name]
    payload = struct.pack(fmt, *[args.pop(n, 0) for n in names])
    if args:
        raise KeyError(f"{name}: unknown arguments {sorted(args)}")
    length = CMD_HEADER.size + len(payload) - 7
    raw = bytearray(CMD_HEADER.pack(mid, 0xC000 | (seq & 0x3FFF), length, fc, 0) + payload)
    raw[7] = _checksum(raw)
    return bytes(raw)


def parse_command(data):
    """Decode a command packet; returns (name, args) or raises ValueError."""
    mid, _seq, length, fc, _cks = CMD_HEADER.unpack_from(data)
    if length != len(data) - 7:
        raise ValueError("length field does not match packet size")
    x = 0
    for b in data:
        x ^= b
    if x != 0xFF:
        raise ValueError("bad checksum")
    name = CMD_BY_ID.get((mid, fc))
    if name is None:
        raise ValueError(f"unknown command MID 0x{mid:04X} FC {fc}")
    _mid, _fc, fmt, names = CMD[name]
    return name, dict(zip(names, struct.unpack(fmt, data[CMD_HEADER.size:])))


def build_telemetry(name, seconds=0, subseconds=0, seq=0, **fields):
    """Encode a telemetry packet; missing fields are zero."""
    mid, fmt, names = TLM[name]
    payload = struct.pack(fmt, *[fields.pop(n, b"" if n in STRING_FIELDS.get(name, ()) else 0) for n in names])
    if fields:
        raise KeyError(f"{name}: unknown fields {sorted(fields)}")
    length = TLM_HEADER.size + len(payload) - 7
    return TLM_HEADER.pack(mid, 0xC000 | (seq & 0x3FFF), length, seconds, subseconds, 0) + payload


def parse_telemetry(data):
    """Decode a telemetry packet; returns (name, header dict, fields dict)."""
    mid, seq, length, seconds, subseconds, _spare = TLM_HEADER.unpack_from(data)
    name = TLM_BY_MID.get(mid)
    if name is None:
        raise ValueError(f"unknown telemetry MID 0x{mid:04X}")
    if length != len(data) - 7:
        raise ValueError("length field does not match packet size")
    _mid, fmt, names = TLM[name]
    values = struct.unpack(fmt, data[TLM_HEADER.size:])
    header = {"seq": seq & 0x3FFF, "seconds": seconds, "subseconds": subseconds}
    return name, header, dict(zip(names, values))


def pack_can(name, **fields):
    msg_type, src, fmt, names = CAN[name]
    data = struct.pack(fmt, *[fields.pop(n, 0) for n in names])
    if fields:
        raise KeyError(f"CAN {name}: unknown fields {sorted(fields)}")
    return data


def unpack_can(name, data):
    _type, _src, fmt, names = CAN[name]
    return dict(zip(names, struct.unpack(fmt, data)))
'''


def gen_python(icd):
    o = [f'"""{HEADER_NOTE}"""', "import struct", "",
         f'ICD_VERSION = "{icd["version"]}"', ""]
    for name, e in icd["enums"].items():
        o.append(f"{name.upper()} = {dict(e['values'])!r}")
    o += ["", "# name: (mid, payload struct format, field names)", "TLM = {"]
    strings = {}
    for p in icd["tlm"]:
        fmt, names = py_fmt(p["fields"])
        o.append(f"    {p['name']!r}: (0x{p['mid']:04X}, {fmt!r}, {names!r}),")
        s = [f["name"] for f in p["fields"] if f["type"] == "char"]
        if s:
            strings[p["name"]] = tuple(s)
    o += ["}", "TLM_BY_MID = {v[0]: k for k, v in TLM.items()}",
          f"STRING_FIELDS = {strings!r}", "",
          "# name: (mid, fc, argument struct format, argument names)", "CMD = {"]
    for c in icd["cmds"]:
        fmt, names = py_fmt(c["fields"])
        o.append(f"    {c['name']!r}: (0x{c['mid']:04X}, {c['fc']}, {fmt!r}, {names!r}),")
    o += ["}", "CMD_BY_ID = {(v[0], v[1]): k for k, v in CMD.items()}", "",
          "# name: (type, source node or 'ANY', payload struct format, field names)", "CAN = {"]
    for m in icd["can"]:
        fmt, names = py_fmt(m["fields"])
        o.append(f"    {m['name']!r}: (0x{m['type']:02X}, {m['src']!r}, {fmt!r}, {names!r}),")
    o += ["}", "CAN_BY_TYPE = {v[0]: k for k, v in CAN.items()}"]
    return "\n".join(o) + "\n" + PY_RUNTIME


