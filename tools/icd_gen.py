def cosmos_desc(f):
    return (f.get("desc") or f["name"].replace("_", " ").capitalize()).replace('"', "'")


def cosmos_items(fields, enums, command):
    lines = []
    for f in fields:
        size, _, _, ctype, signed = TYPES[f["type"]]
        names = [f["name"]] if f["count"] == 1 or f["type"] == "char" else \
            [f"{f['name']}_{i}" for i in range(f["count"])]
        bits = size * 8 * (f["count"] if f["type"] == "char" else 1)
        for nm in names:
            if command:
                if ctype == "FLOAT":
                    rng = "MIN_FLOAT32 MAX_FLOAT32 0.0"
                else:
                    lim = f"{'' if signed else 'U'}INT{bits}"
                    rng = f"MIN_{lim} MAX_{lim} 0"
                lines.append(f'  APPEND_PARAMETER {nm} {bits} {ctype} {rng} "{cosmos_desc(f)}"')
            else:
                lines.append(f'  APPEND_ITEM {nm} {bits} {ctype} "{cosmos_desc(f)}"')
            if f.get("units"):
                lines.append(f'    UNITS "{f["units"]}" "{f["units"]}"')
            if "enum" in f:
                for k, v in enums[f["enum"]]["values"].items():
                    lines.append(f"    STATE {k} {v}")
    return lines


def gen_cosmos_tlm(icd):
    o = [f"# {HEADER_NOTE}", ""]
    for p in icd["tlm"]:
        o += [f'TELEMETRY FLATSAT {p["name"]} LITTLE_ENDIAN "{p["desc"]}"',
              f'  APPEND_ID_ITEM CCSDS_STREAMID 16 UINT 0x{p["mid"]:04X} "CCSDS packet identification" BIG_ENDIAN',
              '  APPEND_ITEM CCSDS_SEQUENCE 16 UINT "CCSDS packet sequence control" BIG_ENDIAN',
              '  APPEND_ITEM CCSDS_LENGTH 16 UINT "CCSDS packet data length" BIG_ENDIAN',
              '  APPEND_ITEM CCSDS_SECONDS 32 UINT "Time: seconds since J2000" BIG_ENDIAN',
              '  APPEND_ITEM CCSDS_SUBSECS 16 UINT "Time: subseconds (2^-16 s)" BIG_ENDIAN',
              '  APPEND_ITEM CCSDS_SPARE 32 UINT "Header spare"']
        o += cosmos_items(p["fields"], icd["enums"], command=False)
        o.append("")
    return "\n".join(o)


def gen_cosmos_cmd(icd):
    o = [f"# {HEADER_NOTE}",
         "# CCSDS_CHECKSUM must make the XOR of all packet bytes equal 0xFF (ICD 3.2);",
         "# the FlatSat interfaces fill it in with lib/flatsat_checksum_protocol.rb.", ""]
    for c in icd["cmds"]:
        o += [f'COMMAND FLATSAT {c["name"]} LITTLE_ENDIAN "{c["desc"] or c["name"]}"',
              f'  APPEND_ID_PARAMETER CCSDS_STREAMID 16 UINT MIN_UINT16 MAX_UINT16 0x{c["mid"]:04X} '
              f'"CCSDS packet identification" BIG_ENDIAN',
              '  APPEND_PARAMETER CCSDS_SEQUENCE 16 UINT MIN_UINT16 MAX_UINT16 0xC000 '
              '"CCSDS packet sequence control" BIG_ENDIAN',
              f'  APPEND_PARAMETER CCSDS_LENGTH 16 UINT MIN_UINT16 MAX_UINT16 {c["total_len"] - 7} '
              f'"CCSDS packet data length" BIG_ENDIAN',
              f'  APPEND_ID_PARAMETER CCSDS_FC 8 UINT MIN_UINT8 MAX_UINT8 {c["fc"]} "Function code"',
              '  APPEND_PARAMETER CCSDS_CHECKSUM 8 UINT MIN_UINT8 MAX_UINT8 0 "Command checksum"']
        o += cosmos_items(c["fields"], icd["enums"], command=True)
        o.append("")
    return "\n".join(o)


