def layout(fields, where):
    """Return fields with offsets and sizes; enforce natural alignment."""
    out = []
    offset = 0
    for f in fields or []:
        if f["name"].lower() in RESERVED:
            raise IcdError(f"{where}.{f['name']}: field name is a C or Python keyword")
        if f["type"] not in TYPES:
            raise IcdError(f"{where}.{f['name']}: unknown type {f['type']}")
        size, *_ = TYPES[f["type"]]
        count = f.get("count", 1)
        if f["type"] == "char" and "count" not in f:
            raise IcdError(f"{where}.{f['name']}: char fields need a count")
        if offset % size:
            raise IcdError(f"{where}.{f['name']}: offset {offset} is not aligned to {size} bytes; "
                           f"add a spare field before it")
        out.append(dict(f, offset=offset, size=size * count, count=count))
        offset += size * count
    return out, offset


def load(path=SOURCE):
    data = yaml.safe_load(path.read_text())
    enums = data["enums"]

    # YAML 1.1 turns unquoted OFF/ON/YES/NO into booleans ("Norway problem"); names must be identifiers
    for ename, e in enums.items():
        for key in e["values"]:
            if not isinstance(key, str) or not re.fullmatch(r"[A-Z][A-Z0-9_]*", key):
                raise IcdError(f"enum {ename}: value name {key!r} must be an UPPER_CASE identifier "
                               f"(quote OFF/ON/YES/NO in the YAML)")

    def check_enums(fields, where):
        for f in fields:
            if "enum" in f and f["enum"] not in enums:
                raise IcdError(f"{where}.{f['name']}: unknown enum {f['enum']}")

    mids = {}
    tlm = []
    for p in data["telemetry"]:
        fields, size = layout(p["fields"], p["name"])
        check_enums(fields, p["name"])
        if not 0x0800 <= p["mid"] <= 0x0FFF:
            raise IcdError(f"{p['name']}: telemetry MID 0x{p['mid']:04X} must have the TM type bit clear")
        if p["mid"] in mids:
            raise IcdError(f"{p['name']}: MID 0x{p['mid']:04X} already used by {mids[p['mid']]}")
        mids[p["mid"]] = p["name"]
        total = TLM_HDR_LEN + size
        if total > RF_MAX_PACKET:
            raise IcdError(f"{p['name']}: {total} bytes exceeds the RF packet limit of {RF_MAX_PACKET}")
        tlm.append(dict(p, fields=fields, payload_len=size, total_len=total))

    cmds = []
    for group in data["commands"]:
        if not 0x1800 <= group["mid"] <= 0x1FFF:
            raise IcdError(f"{group['prefix']}: command MID 0x{group['mid']:04X} must have the TC type bit set")
        if group["mid"] in mids:
            raise IcdError(f"{group['prefix']}: MID 0x{group['mid']:04X} already used by {mids[group['mid']]}")
        mids[group["mid"]] = group["prefix"]
        fcs = set()
        for c in group["commands"]:
            name = f"{group['prefix']}_{c['name']}"
            if c["fc"] in fcs:
                raise IcdError(f"{name}: function code {c['fc']} used twice in MID 0x{group['mid']:04X}")
            fcs.add(c["fc"])
            fields, size = layout(c.get("fields"), name)
            check_enums(fields, name)
            total = CMD_HDR_LEN + size
            if total > RF_MAX_PACKET:
                raise IcdError(f"{name}: {total} bytes exceeds the RF packet limit")
            cmds.append(dict(c, name=name, short=c["name"], prefix=group["prefix"], mid=group["mid"],
                             fields=fields, payload_len=size, total_len=total, desc=c.get("desc", "")))

    can = []
    types = {}
    for m in data["can"]:
        fields, size = layout(m["fields"], f"CAN {m['name']}")
        check_enums(fields, m["name"])
        if size > CAN_MAX_DLC:
            raise IcdError(f"CAN {m['name']}: {size} bytes exceeds {CAN_MAX_DLC}")
        if not 0 < m["type"] < 0x80:
            raise IcdError(f"CAN {m['name']}: type must be 1..127")
        if m["type"] in types:
            raise IcdError(f"CAN {m['name']}: type 0x{m['type']:02X} already used by {types[m['type']]}")
        types[m["type"]] = m["name"]
        if m["src"] != "ANY" and m["src"] not in enums["node"]["values"]:
            raise IcdError(f"CAN {m['name']}: unknown source node {m['src']}")
        can.append(dict(m, fields=fields, dlc=size))

    return dict(version=data["version"], enums=enums, tlm=tlm, cmds=cmds, can=can)


