#!/usr/bin/env python3
"""Generate interface artefacts from docs/icd/flatsat_icd.yaml.

Outputs (all marked "generated, do not edit"):
    firmware/common/include/flatsat_icd.h       C structs, IDs, lengths, X-macro tables
    ground/flatsat_icd.py                       Python codec for ground software and tests
    nos3/components/hil_bridge/gsw/FLATSAT/cmd_tlm/FLATSAT_TLM.txt
    nos3/components/hil_bridge/gsw/FLATSAT/cmd_tlm/FLATSAT_CMD.txt
                                                COSMOS 4 packet definitions (NOS3's COSMOS build copies
                                                components/*/gsw into its configuration)
    docs/icd/ICD_layouts.md                     Byte-level layout tables

Usage:
    python3 tools/icd_gen.py           regenerate
    python3 tools/icd_gen.py --check   exit 1 if any generated file is out of date (for CI)
"""
import argparse
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/icd/flatsat_icd.yaml"

TLM_HDR_LEN = 16
CMD_HDR_LEN = 8
RF_MAX_PACKET = 249
CAN_MAX_DLC = 8

# type -> (size, C type, struct code, COSMOS type, signed)
TYPES = {
    "u8": (1, "uint8_t", "B", "UINT", False),
    "u16": (2, "uint16_t", "H", "UINT", False),
    "u32": (4, "uint32_t", "I", "UINT", False),
    "i8": (1, "int8_t", "b", "INT", True),
    "i16": (2, "int16_t", "h", "INT", True),
    "i32": (4, "int32_t", "i", "INT", True),
    "f32": (4, "float", "f", "FLOAT", True),
    "char": (1, "char", "s", "STRING", False),
}

HEADER_NOTE = "Generated by tools/icd_gen.py from docs/icd/flatsat_icd.yaml. Do not edit."

# Field names become C struct members and Python identifiers, so neither language's keywords are allowed
RESERVED = {
    "auto", "break", "case", "char", "const", "continue", "default", "do", "double", "else", "enum", "extern",
    "float", "for", "goto", "if", "inline", "int", "long", "register", "restrict", "return", "short", "signed",
    "sizeof", "static", "struct", "switch", "typedef", "union", "unsigned", "void", "volatile", "while", "bool",
    "and", "as", "assert", "async", "await", "class", "def", "del", "elif", "except", "finally", "from",
    "global", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "try", "with", "yield",
}


class IcdError(Exception):
    pass


