def c_fields(fields):
    lines = []
    for f in fields:
        _, ctype, *_ = TYPES[f["type"]]
        arr = f"[{f['count']}]" if f["count"] > 1 or f["type"] == "char" else ""
        note = " ".join(x for x in [f.get("units", ""), f.get("desc", "")] if x)
        if "enum" in f:
            note = (note + f" (flatsat_{f['enum']}_t)").strip()
        comment = f" /* {note} */" if note else ""
        lines.append(f"    {ctype} {f['name'].lower()}{arr};{comment}")
    return lines


def gen_c(icd):
    o = [f"/* {HEADER_NOTE} */",
         "#ifndef FLATSAT_ICD_H", "#define FLATSAT_ICD_H", "",
         "#include <stdint.h>", "",
         f'#define FLATSAT_ICD_VERSION "{icd["version"]}"',
         f"#define FLATSAT_TLM_HDR_LEN {TLM_HDR_LEN}",
         f"#define FLATSAT_CMD_HDR_LEN {CMD_HDR_LEN}",
         f"#define FLATSAT_RF_MAX_PACKET {RF_MAX_PACKET}", "",
         "/* CAN ID = message type << 4 | source node (ICD 6.2) */",
         "#define FLATSAT_CAN_ID(type, node) ((uint16_t)(((type) << 4) | (node)))",
         "#define FLATSAT_CAN_TYPE(id) ((uint8_t)((id) >> 4))",
         "#define FLATSAT_CAN_NODE(id) ((uint8_t)((id) & 0x0F))", "",
         "/* ---- Enumerations ---- */", ""]
    for name, e in icd["enums"].items():
        if e.get("desc"):
            o.append(f"/* {e['desc']} */")
        o.append("typedef enum")
        o.append("{")
        for k, v in e["values"].items():
            o.append(f"    FLATSAT_{name.upper()}_{k} = {v},")
        o.append(f"}} flatsat_{name}_t;")
        o.append("")

    o += ["/* ---- Telemetry packets: payload follows the 16-byte header ---- */", ""]
    for p in icd["tlm"]:
        n = p["name"]
        o.append(f"/* {p['desc']} */")
        o.append(f"#define FLATSAT_{n}_MID 0x{p['mid']:04X}")
        o.append(f"#define FLATSAT_{n}_LEN {p['total_len']}")
        o.append("typedef struct __attribute__((packed))")
        o.append("{")
        o += c_fields(p["fields"])
        o.append(f"}} flatsat_{n.lower()}_t;")
        o.append(f'_Static_assert(sizeof(flatsat_{n.lower()}_t) == {p["payload_len"]}, "{n} layout");')
        o.append("")

    o += ["/* ---- Commands: arguments follow the 8-byte header ---- */", ""]
    for group in sorted({(c["prefix"], c["mid"]) for c in icd["cmds"]}, key=lambda g: g[1]):
        o.append(f"#define FLATSAT_{group[0]}_CMD_MID 0x{group[1]:04X}")
    o.append("")
    for c in icd["cmds"]:
        n = c["name"]
        o.append(f"#define FLATSAT_{n}_FC {c['fc']}")
        o.append(f"#define FLATSAT_{n}_LEN {c['total_len']}")
        if c["fields"]:
            o.append("typedef struct __attribute__((packed))")
            o.append("{")
            o += c_fields(c["fields"])
            o.append(f"}} flatsat_{n.lower()}_t;")
            o.append(f'_Static_assert(sizeof(flatsat_{n.lower()}_t) == {c["payload_len"]}, "{n} layout");')
        o.append("")

    o += ["/* ---- CAN messages (ICD 6.3) ---- */", ""]
    for m in icd["can"]:
        n = m["name"]
        src = "any node" if m["src"] == "ANY" else m["src"]
        period = f"every {m['period_ms']} ms" if m["period_ms"] else "on event"
        o.append(f"/* {n}: from {src}, {period} */")
        o.append(f"#define FLATSAT_CAN_{n}_TYPE 0x{m['type']:02X}")
        o.append(f"#define FLATSAT_CAN_{n}_DLC {m['dlc']}")
        o.append(f"#define FLATSAT_CAN_{n}_PERIOD_MS {m['period_ms']}")
        o.append("typedef struct __attribute__((packed))")
        o.append("{")
        o += c_fields(m["fields"])
        o.append(f"}} flatsat_can_{n.lower()}_t;")
        o.append(f'_Static_assert(sizeof(flatsat_can_{n.lower()}_t) == {m["dlc"]}, "CAN {n} layout");')
        o.append("")

    o += ["/* ---- Tables for dispatchers and schedulers ---- */",
          "/* X(name, mid, total_len) */",
          "#define FLATSAT_TLM_LIST(X) \\"]
    o += [f"    X({p['name']}, 0x{p['mid']:04X}, {p['total_len']}) \\" for p in icd["tlm"]]
    o += ["", "/* X(name, mid, fc, total_len) */", "#define FLATSAT_CMD_LIST(X) \\"]
    o += [f"    X({c['name']}, 0x{c['mid']:04X}, {c['fc']}, {c['total_len']}) \\" for c in icd["cmds"]]
    o += ["", "/* X(name, type, dlc, period_ms) */", "#define FLATSAT_CAN_LIST(X) \\"]
    o += [f"    X({m['name']}, 0x{m['type']:02X}, {m['dlc']}, {m['period_ms']}) \\" for m in icd["can"]]
    o += ["", "#endif /* FLATSAT_ICD_H */", ""]
    return "\n".join(o)


